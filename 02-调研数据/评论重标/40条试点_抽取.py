rows = []
idx = 0
for plat, titles in curated.items():
    for t in titles:
        sub = post[(post['平台'] == plat) & (post['内容标题'].astype(str).str.contains(re.escape(t), regex=True))]
        if sub.empty:
            print('MISS', plat, t)
            continue
        r = sub.iloc[0]
        idx += 1
        cid = str(r['平台内容ID'])
        cm = wide[wide['内容ID'] == cid].copy()
        cm['赞'] = pd.to_numeric(cm['评论点赞数'], errors='coerce').fillna(0)
        cm = cm.sort_values('赞', ascending=False).head(10)
        top = []
        for _, c in cm.iterrows():
            txt = str(c['评论正文']).replace('\n', ' ').replace('\r', ' ')
            txt = re.sub(r'\s+', ' ', txt)[:180]
            top.append(f"[赞{int(c['赞'])}] {txt}")
        rows.append({
            '编号': f'P{idx:02d}',
            '平台': plat,
            '搜索词': r['抓取搜索词'],
            '标题': str(r['内容标题'])[:120],
            '正文摘要': re.sub(r'\s+', ' ', str(r['正文/详情摘要']))[:600],
            '作者': r['作者昵称'],
            '点赞': r['点赞数'],
            '总评论': r['原帖总评论数'],
            '已抓评论': r['本库已抓评论数'],
            'Top10评论': ' || '.join(top),
            '链接': r['原帖验证链接(URL)'],
            '内容ID': cid,
        })

df = pd.DataFrame(rows)
