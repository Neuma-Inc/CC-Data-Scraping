# 评论问句密度
qpat = re.compile(r'[?？]|怎么|能不能|可以吗|为什么|怎么办|多少|求|有没有|正常吗|建议')
def split_c(s):
    if pd.isna(s): return []
    return [x.strip() for x in str(s).split('||') if x.strip()]
df['Top评论数'] = df['Top10评论'].apply(lambda s: len(split_c(s)))
df['含问句评论数'] = df['Top10评论'].apply(lambda s: sum(1 for c in split_c(s) if qpat.search(c)))

