# -*- coding: utf-8 -*-
import pandas as pd
p = r'D:\A-灵知生物\小程序\05-市场调研\02-调研数据\评论重标\400条编码\400条编码_小红书.csv'
df = pd.read_csv(p, encoding='utf-8-sig')

print('--- 逻辑一致性 ---')
print('求助帖但卡点=否:', df[(df['帖子类型']=='用户求助') & (df['卡点可编码性']=='否')]['编号'].tolist())
print('求助帖但问题=无:', df[(df['帖子类型']=='用户求助') & (df['具体问的问题（原话）'].str.startswith('无'))]['编号'].tolist())
print('非求助但有具体问题:', df[(df['帖子类型']!='用户求助') & (~df['具体问的问题（原话）'].str.startswith('无'))]['编号'].tolist())
print('经历/吐槽但触发=不适用:', df[(df['帖子类型'].isin(['用户经历','用户吐槽'])) & (df['触发事件']=='不适用')]['编号'].tolist())
print('卡点=是但试过=不适用:', df[(df['卡点可编码性']=='是') & (df['试过什么']=='不适用')]['编号'].tolist())
print('科普/广告但卡点!=否:', df[(df['帖子类型'].isin(['博主科普','广告/服务'])) & (df['卡点可编码性']!='否')]['编号'].tolist())

print('\n--- 全部90行速览 ---')
for _, r in df.iterrows():
    print(f"{r['编号']} | {r['帖子类型']} | {r['卡点可编码性']} | {r['置信度']} | {r['搜索词'][:12]} | {str(r['卡在哪'])[:34]}")
