# 允许的拉丁健康词
ALLOW_LATIN = re.compile(r"^(NAD|NMN|HPV|PM2\.5|CT|B超|TCT|HPV疫苗)", re.I)


def clean_name(n):
    return (n or "").strip().lstrip("#").strip()


def main():
    idx = json.load(open(os.path.join(CACHE, "douyin_hashtag_index_big.json"), encoding="utf-8"))
    print("index size", len(idx))

    # 词根按长度降序，保证「多囊卵巢」优先于「多囊」
    root_list = []
    for cat, roots in ROOTS.items():
        for r in roots:
            root_list.append((r, cat))
    root_list.sort(key=lambda x: -len(x[0]))

    rows = {}
    for name, cid in idx.items():
        n = clean_name(name)
        if not (2 <= len(n) <= 18):
            continue
        if re.search(r"[#@【】\[\]（）()「」\"“”'’,，。.!！?？:：;；/\\|~\-—_+=*&%$^<>]", n):
            continue
        if NOISE.search(n):
            continue
        if not re.search(r"[\u4e00-\u9fff]", n) and not ALLOW_LATIN.search(n):
            continue

        hit = None
        for root, cat in root_list:
            if root in n:
                hit = (root, cat)
                break
        if not hit:
            continue
        root, cat = hit
        # 短名（<= root+3）直接收；长名必须带健康意图后缀
        if len(n) > len(root) + 3 and not INTENT.search(n):
            continue
        # 纯词根重复/无意义扩展过滤
        if n in {root} or len(n) <= 8 or INTENT.search(n):
            key = n
            if key not in rows:
                rows[key] = {"category_18": cat, "topic": n, "challenge_id": str(cid),
                             "root": root, "name_len": len(n)}
    out_rows = sorted(rows.values(), key=lambda r: (r["category_18"], r["name_len"], r["topic"]))
    print("total unique", len(out_rows))
    from collections import Counter
    c = Counter(r["category_18"] for r in out_rows)
    for cat in ROOTS:
        print(f"  {cat}: {c.get(cat,0)}")

    out = os.path.join(OUT, "douyin_topic_candidates.csv")
    with open(out, "w", encoding="utf-8-sig", newline="") as f:
        w = csv.DictWriter(f, fieldnames=["category_18", "topic", "challenge_id", "root", "name_len"])
        w.writeheader()
        w.writerows(out_rows)
    print("->", out)

    with open(os.path.join(OUT, "douyin_topic_candidates_sample.txt"), "w", encoding="utf-8") as f:
        for cat in ROOTS:
            sub = [r["topic"] for r in out_rows if r["category_18"] == cat]
            f.write(f"\n## {cat} ({len(sub)})\n" + "、".join(sub[:60]) + "\n")
            print(f"\n## {cat} ({len(sub)})\n" + "、".join(sub[:30]))


if __name__ == "__main__":
    main()
