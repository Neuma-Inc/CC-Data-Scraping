def clean_name(n):
    return (n or "").strip().lstrip("#").strip()


def main():
    idx = json.load(open(os.path.join(CACHE, "douyin_hashtag_index_big.json"), encoding="utf-8"))
    print("index size", len(idx))

    seed_pairs = []
    for cat, seeds in SEEDS.items():
        for s in seeds:
            seed_pairs.append((s, cat))
    seed_pairs.sort(key=lambda x: -len(x[0]))

    rows = {}
    for name, cid in idx.items():
        n = clean_name(name)
        if not (2 <= len(n) <= 20):
            continue
        if re.search(r"[#@【】\[\]（）()「」\"“”'’,，。.!！?？:：;；/\\|~\-—_+=*&%$^<>]", n):
            continue
        if NOISE.search(n):
            continue
        hit = None
        for seed, cat in seed_pairs:
            if seed in n:
                hit = (seed, cat)
                break
        if not hit:
            continue
        seed, cat = hit
        if seed in CONTEXT_REQUIRED and not re.search(CONTEXT_REQUIRED[seed], n):
            continue
        # 长度规则：等于词根、或以词根开头且短、或带意图后缀
        if len(n) > len(seed) + 6 and not SUFFIX.search(n):
            continue
        if n not in rows:
            rows[n] = {"category_18": cat, "topic": n, "challenge_id": str(cid),
                       "root": seed, "name_len": len(n)}

    out_rows = sorted(rows.values(), key=lambda r: (r["category_18"], r["name_len"], r["topic"]))
    from collections import Counter
    c = Counter(r["category_18"] for r in out_rows)
    print("total unique", len(out_rows))
    for cat in SEEDS:
        print(f"  {cat}: {c.get(cat,0)}")

    out = os.path.join(OUT, "douyin_topic_candidates.csv")
    with open(out, "w", encoding="utf-8-sig", newline="") as f:
        w = csv.DictWriter(f, fieldnames=["category_18", "topic", "challenge_id", "root", "name_len"])
        w.writeheader()
        w.writerows(out_rows)
    print("->", out)

    with open(os.path.join(OUT, "douyin_topic_candidates_sample.txt"), "w", encoding="utf-8") as f:
        for cat in SEEDS:
            sub = [r["topic"] for r in out_rows if r["category_18"] == cat]
            f.write(f"\n## {cat} ({len(sub)})\n" + "、".join(sub[:80]) + "\n")
            print(f"\n## {cat} ({len(sub)})\n" + "、".join(sub[:35]))


if __name__ == "__main__":
    main()
